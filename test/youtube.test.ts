import assert from "node:assert/strict";
import { test } from "node:test";
import {
  isPlaceholderInfo,
  parseYtTopicVideoDescription,
  processYtVideoTitle,
  stripTopicSuffix,
  trackFromVideoTitle,
  trackFromYtdlp,
} from "../src/main/youtube.ts";

test("processYtVideoTitle: common title shapes", () => {
  const cases: [string, string | null, string | null][] = [
    ["Artist - Song (Official Video)", "Artist", "Song (Official Video)"],
    ['Artist "Song"', "Artist", "Song"],
    ['Artist: "Song"', "Artist", "Song"],
    ["アーティスト「曲名」MV", "アーティスト", "曲名"],
    ["アーティスト『曲名』", "アーティスト", "曲名"],
    ["【MV】アーティスト - 曲名", "アーティスト", "曲名"],
    ["[Electronic] Artist - Song", "Artist", "Song"],
    ["01. Artist - Song", "Artist", "Song"],
    ["Song (cover by Someone)", "Someone", "Song"],
    ["アーティスト【曲名】", "アーティスト", "曲名"],
    ["Just a title", null, "Just a title"],
  ];
  for (const [title, artist, track] of cases) {
    assert.deepEqual(processYtVideoTitle(title), { artist, track }, title);
  }
});

const TOPIC_DESC = [
  "Provided to YouTube by Label Records",
  "",
  "Song Title · Main Artist",
  "",
  "Album Name",
  "",
  "℗ 2020 Label Records",
  "",
  "Released on: 2020-01-01",
  "",
  "Auto-generated by YouTube.",
].join("\n");

test("parseYtTopicVideoDescription reads track, artist and album", () => {
  assert.deepEqual(parseYtTopicVideoDescription(TOPIC_DESC), { artist: "Main Artist", track: "Song Title", album: "Album Name" });
});

test("parseYtTopicVideoDescription adds featured artists unless already in the title", () => {
  const feat = TOPIC_DESC.replace("Song Title · Main Artist", "Song Title · Main Artist · Guest");
  assert.equal(parseYtTopicVideoDescription(feat)?.track, "Song Title (feat. Guest)");
  const already = TOPIC_DESC.replace("Song Title · Main Artist", "Song Title (feat. Guest) · Main Artist · Guest");
  assert.equal(parseYtTopicVideoDescription(already)?.track, "Song Title (feat. Guest)");
});

test("parseYtTopicVideoDescription ignores ordinary descriptions", () => {
  assert.equal(parseYtTopicVideoDescription("Check out my new video!\nFollow me"), null);
  assert.equal(parseYtTopicVideoDescription(null), null);
});

test("stripTopicSuffix", () => {
  assert.equal(stripTopicSuffix("Main Artist - Topic"), "Main Artist");
  assert.equal(stripTopicSuffix("アーティスト - トピック"), "アーティスト");
  assert.equal(stripTopicSuffix("Plain Channel"), "Plain Channel");
});

test("trackFromYtdlp: music fields first, main artist only (as seen on device: YOASOBI, Ayase)", () => {
  const r = trackFromYtdlp({ artist: "YOASOBI，Ayase", artists: ["YOASOBI", "Ayase"], track: "夜に駆ける", album: "Al", title: "whatever", duration: 200 });
  assert.deepEqual(r, { ok: true, from: "ytdlp-music", track: { artist: "YOASOBI", track: "夜に駆ける", album: "Al", duration: 200 } });
});

test("trackFromYtdlp: topic description next", () => {
  const r = trackFromYtdlp({ title: "Song Title", channel: "Main Artist - Topic", description: TOPIC_DESC });
  assert.deepEqual(r.ok && [r.from, r.track.artist, r.track.track, r.track.album], ["ytdlp-description", "Main Artist", "Song Title", "Album Name"]);
});

test("trackFromYtdlp: title, with the channel as artist when the title has none", () => {
  const split = trackFromYtdlp({ title: "Artist - Song", channel: "Label" });
  assert.deepEqual(split.ok && [split.from, split.track.artist, split.track.track], ["ytdlp-title", "Artist", "Song"]);
  const channel = trackFromYtdlp({ title: "Song", channel: "Artist - Topic" });
  assert.deepEqual(channel.ok && [channel.track.artist, channel.track.track], ["Artist", "Song"]);
  // Same as web-scrobbler: any video becomes "channel - title" (turn the yt-dlp source off to avoid this)
  const vlog = trackFromYtdlp({ title: "My day in Tokyo", channel: "Vlogger" });
  assert.deepEqual(vlog.ok && [vlog.track.artist, vlog.track.track], ["Vlogger", "My day in Tokyo"]);
});

test("trackFromYtdlp: live streams are skipped", () => {
  const r = trackFromYtdlp({ title: "Artist - Song", channel: "C", is_live: true });
  assert.deepEqual(r, { ok: false, reason: "live stream", live: true });
});

test("placeholder results for unknown videos are recognised", () => {
  assert.equal(isPlaceholderInfo({ title: "youtube video #abc", channel: null, uploader: null, description: null }), true);
  assert.equal(isPlaceholderInfo({ title: "Real title", channel: "C" }), false);
});

test("trackFromVideoTitle needs an artist in the title", () => {
  assert.equal(trackFromVideoTitle("Artist - Song").ok, true);
  assert.equal(trackFromVideoTitle("Song only").ok, false);
});
