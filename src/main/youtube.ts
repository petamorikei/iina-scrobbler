// Track info for videos played through yt-dlp (docs/design.md §4.2).
//
// processYtVideoTitle, parseYtTopicVideoDescription and the "- Topic" channel suffix
// are ported from web-scrobbler (src/core/content/util.ts, src/connectors/youtube.ts).
// web-scrobbler: Copyright (c) 2010-2023 David Šabata & Web Scrobbler Team, MIT License.
import type { Track } from "../services/types.ts";
import { clean, splitArtistTitle } from "./title-parser.ts";

export interface ArtistTrack {
  artist: string | null;
  track: string | null;
}

const ARTIST_SEPARATOR = ", ";

const YT_TITLE_REGEXPS: { pattern: RegExp; artist: number; track: number }[] = [
  // Artist "Track", Artist: "Track", Artist - "Track", etc.
  { pattern: /(.+?)([\s:—-])+\s*"(.+?)"/, artist: 1, track: 3 },
  // Artist「Track」 (Japanese tracks)
  { pattern: /(.+?)[『｢「](.+?)[」｣』]/, artist: 1, track: 2 },
  // Track (... by Artist)
  { pattern: /(\w[\s\w]*?)\s+\([^)]*\s*by\s*([^)]+)+\)/, artist: 2, track: 1 },
];

/** Extracts artist and track from a YouTube video title (web-scrobbler's rules). */
export function processYtVideoTitle(videoTitle: string | null | undefined): ArtistTrack {
  if (!videoTitle) return { artist: null, track: null };

  // Remove [genre] or 【genre】 from the beginning of the title
  let title = videoTitle.replace(/^((\[[^\]]+\])|(【[^】]+】))\s*-*\s*/i, "");
  // Remove track (CD and vinyl) numbers from the beginning of the title
  title = title.replace(/^\s*([a-zA-Z]{1,2}|[0-9]{1,2})[1-9]?\.\s+/i, "");
  // Remove - preceding opening bracket
  title = title.replace(/-\s*([「【『])/, "$1");
  // 【/(*Music Video/MV/PV*】/)
  title = title.replace(/[(［【][^(［【]*?((Music Video)|(MV)|(PV)).*?[】］)]/i, "");
  // 【/(東方/オリジナル*】/)
  title = title.replace(/[(［【]((オリジナル)|(東方)).*?[】］)]+?/, "");
  // MV/PV if followed by an opening/closing bracket
  title = title.replace(/((?:Music Video)|MV|PV)([「［【『』】］」])/i, "$2");
  // MV/PV if ending and with whitespace in front
  title = title.replace(/\s+(MV|PV)$/i, "");

  for (const re of YT_TITLE_REGEXPS) {
    const m = re.pattern.exec(title);
    if (m) {
      const artist = clean(m[re.artist]);
      const track = clean(m[re.track]);
      if (artist && track) return { artist, track };
    }
  }

  const split = splitArtistTitle(title);
  if (split) return { artist: split.artist, track: split.title };

  const bracket = /(.+?)【(.+?)】/.exec(title);
  if (bracket && clean(bracket[1]) && clean(bracket[2])) return { artist: clean(bracket[1]), track: clean(bracket[2]) };

  return { artist: null, track: clean(title) || null };
}

const YT_DESC_FIRST_LINE = "Provided to YouTube";
const YT_DESC_LAST_LINE = "Auto-generated by YouTube.";
const YT_DESC_SEPARATOR = " · ";

/**
 * Parses the description of a YouTube Music auto-generated ("Topic") video:
 *   Provided to YouTube by <label>
 *   <Track> · <Artist> · <Featured artist>...
 *   <Album>
 */
export function parseYtTopicVideoDescription(desc: string | null | undefined): (ArtistTrack & { album: string | null }) | null {
  if (!desc || !(desc.startsWith(YT_DESC_FIRST_LINE) || desc.trimEnd().endsWith(YT_DESC_LAST_LINE))) return null;
  const lines = desc
    .split("\n")
    .filter((l) => l.length > 0)
    .filter((l) => !l.startsWith(YT_DESC_FIRST_LINE));
  const first = lines[0];
  if (!first) return null;
  const fields = first.split(YT_DESC_SEPARATOR);
  const album = clean(lines[1]) || null;
  if (fields.length < 2) return { artist: null, track: clean(fields[0]) || null, album };
  if (fields.length === 2) return { artist: clean(fields[1]) || null, track: clean(fields[0]) || null, album };
  const [track = "", artist = "", ...feat] = fields;
  const featPresent = feat.some((a) => track.includes(a));
  const fullTrack = featPresent ? track : `${track} (feat. ${feat.join(ARTIST_SEPARATOR)})`;
  return { artist: clean(artist) || null, track: clean(fullTrack) || null, album };
}

/** "Artist - Topic" → "Artist" (and the localised variants web-scrobbler knows). */
const TOPIC_SUFFIX =
  // eslint-disable-next-line no-irregular-whitespace
  /^(?:Mavzu|Тема|الموضوع|ਵਿਸ਼ਾ)\s[–-]\s|(?:(?:\s[-—–]|[:՝])\s(?:Onderwerp|Mövzu|Topik|tema|Tema|téma|Emne|Thema|teema|Topic|gaia|Paksa|Sujet|Isihloko|Efni|Mada|tēma|téma|emne|temat|Tópico|Subiect|aihekanava|Ämne|Chủ đề|Konu|тэма|Тема|Тақырып|Сэдэв|тема|Θέμα|թեմա|נושא|موضوع|عنوان|विषय|বিষয়বস্তু|বিষয়|મુદ્દો|ବିଷୟ|தலைப்பு|అంశం|ವಿಷಯ|വിഷയം|මාතෘකාව|หัวข้อ|ຫົວ​ຂໍ້|ခေါင်းစဉ်|თემა|ርዕስ|ប្រធាន​បទ|主题|主題|トピック|주제)|\s\(tema\))$/;

export function stripTopicSuffix(channel: string): string {
  return clean(channel.replace(TOPIC_SUFFIX, ""));
}

/** The subset of `yt-dlp -J` output that is used. */
export interface YtdlpInfo {
  id?: string | null;
  title?: string | null;
  track?: string | null;
  artist?: string | null;
  artists?: string[] | null;
  album?: string | null;
  channel?: string | null;
  uploader?: string | null;
  description?: string | null;
  duration?: number | null;
  is_live?: boolean | null;
}

export type YtTrackResult =
  | { ok: true; track: Track; from: "ytdlp-music" | "ytdlp-description" | "ytdlp-title" | "title" }
  | { ok: false; reason: string; live?: boolean };

/**
 * yt-dlp sometimes answers an unknown video with exit code 0, a title of
 * "youtube video #<id>" and nothing else (research.md §8.4).
 */
export function isPlaceholderInfo(info: YtdlpInfo): boolean {
  return /^youtube video #/i.test(info.title ?? "") && !info.channel && !info.uploader && !info.description;
}

/** Same order as web-scrobbler, with yt-dlp's own music fields first. */
export function trackFromYtdlp(info: YtdlpInfo): YtTrackResult {
  if (info.is_live) return { ok: false, reason: "live stream", live: true };
  const duration = typeof info.duration === "number" && info.duration > 0 ? info.duration : undefined;
  const album = clean(info.album) || undefined;

  // 1. Music metadata (YouTube Music / auto-generated videos). `artist` is a joined
  //    string that sometimes uses a full-width comma, so use `artists`, and only its
  //    first entry: the rest are other credits (e.g. ["YOASOBI", "Ayase"]), and a
  //    joined name would be a different artist on Last.fm.
  const artists = (info.artists ?? []).map(clean).filter(Boolean);
  const musicTrack = clean(info.track);
  if (artists[0] && musicTrack) {
    return { ok: true, from: "ytdlp-music", track: { artist: artists[0], track: musicTrack, album, duration } };
  }

  // 2. "Provided to YouTube by ..." description.
  const desc = parseYtTopicVideoDescription(info.description);
  if (desc?.artist && desc.track) {
    return { ok: true, from: "ytdlp-description", track: { artist: desc.artist, track: desc.track, album: desc.album ?? album, duration } };
  }

  // 3. Video title, with the channel name as the artist when the title has none.
  const fromTitle = processYtVideoTitle(info.title);
  const channel = stripTopicSuffix(info.channel || info.uploader || "");
  const artist = fromTitle.artist || channel;
  if (artist && fromTitle.track) {
    return { ok: true, from: "ytdlp-title", track: { artist, track: fromTitle.track, duration } };
  }
  return { ok: false, reason: "no artist/track in yt-dlp metadata" };
}

/** Without yt-dlp: only the video title (media-title) is available. */
export function trackFromVideoTitle(mediaTitle: string, duration?: number): YtTrackResult {
  const { artist, track } = processYtVideoTitle(mediaTitle);
  if (artist && track) return { ok: true, from: "title", track: { artist, track, duration } };
  return { ok: false, reason: "no artist in the video title (yt-dlp metadata unavailable)" };
}
